interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  t: (key: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const languageSwitchEnabled = false;
  const [locale, setLocaleState] = useState<Locale>("zh");

  useEffect(() => {
    if (!languageSwitchEnabled) {
      setLocaleState("zh");
      return;
    }
    try {
      const storedLocale = window.localStorage.getItem(STORAGE_KEY);
      if (storedLocale === "en" || storedLocale === "zh") {
        setLocaleState(storedLocale);
      }
    } catch {
      // Language switching remains available when browser storage is restricted.
    }
  }, [languageSwitchEnabled]);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.documentElement.dataset.locale = locale;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Persistence is optional; the active interface language still changes.
    }
  }, [locale]);

  function t(key: string): string {
    if (!languageSwitchEnabled) {
      return MESSAGES.zh[key] ?? key;
    }
    return MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  }

  return (
    <LocaleContext.Provider
      value={{
        locale,
        setLocale: (nextLocale) => setLocaleState(
          languageSwitchEnabled ? nextLocale : "zh",
        ),
        toggleLocale: () => {
          if (languageSwitchEnabled) {
            setLocaleState((current) => current === "en" ? "zh" : "en");
          }
        },
        t,
      }}
    >
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider.");
  return value;
}
